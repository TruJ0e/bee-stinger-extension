"""Render a self-contained study-guide HTML page from cards + quiz.

The structure follows the TRSS study-unit pattern: the guide content first
(concepts explained), then flashcards, then a leveled self-check quiz.
Single file, inline CSS, no external assets — it can be opened anywhere,
attached anywhere, or embedded into a TRSS unit later.
"""

from __future__ import annotations

import html

_CSS = """
body { font-family: Georgia, 'Times New Roman', serif; margin: 0; background: #faf7f2; color: #1d2733; }
header { background: #123a5f; color: #fff; padding: 28px 24px; }
header h1 { margin: 0 0 6px; font-size: 28px; }
header p { margin: 0; opacity: .85; }
main { max-width: 860px; margin: 0 auto; padding: 24px; }
h2 { border-bottom: 3px solid #f2b705; padding-bottom: 6px; margin-top: 40px; }
.card { background: #fff; border: 1px solid #ddd5c4; border-radius: 10px; padding: 18px 20px; margin: 14px 0; }
.card h3 { margin: 0 0 4px; }
.chip { display: inline-block; background: #eef3f8; border: 1px solid #c9d6e4; border-radius: 999px; padding: 1px 10px; font-size: 12px; margin-right: 6px; }
.apply { background: #fdf6e0; border-left: 4px solid #f2b705; padding: 10px 14px; margin-top: 10px; }
details { background: #fff; border: 1px solid #ddd5c4; border-radius: 10px; padding: 12px 16px; margin: 10px 0; }
summary { cursor: pointer; font-weight: bold; }
.quiz-q { margin: 14px 0; }
.quiz-q ol { margin: 6px 0 6px 18px; }
.commit { background: #eaf5ea; border-left: 4px solid #3d8b4f; padding: 10px 14px; margin: 10px 0; }
footer { max-width: 860px; margin: 0 auto; padding: 0 24px 32px; font-size: 13px; color: #667; }
"""


_COMMIT_LABEL = {"due": "due", "exam": "on", "reading": "before"}


def _esc(s) -> str:
    return html.escape(str(s))


def render_guide(title: str, cards: list[dict], quiz: list[dict], commitments: list[dict]) -> str:
    out: list[str] = []
    out.append("<!DOCTYPE html><html lang='en'><head><meta charset='utf-8'>")
    out.append(f"<title>{_esc(title)} — Study Guide</title><style>{_CSS}</style></head><body>")
    out.append(
        f"<header><h1>{_esc(title)}</h1>"
        f"<p>Study guide generated by Bee Stinger from a Bee lecture capture. "
        f"{len(cards)} concepts, {len(quiz)} quiz questions.</p></header><main>"
    )

    # The guide itself
    out.append("<h2>The Guide</h2>")
    for card in cards:
        out.append("<section class='card'>")
        out.append(f"<h3>{_esc(card['term'])}</h3>")
        out.append(f"<span class='chip'>{_esc(card['type'])}</span><span class='chip'>{_esc(card['category'])}</span>")
        out.append(f"<p>{_esc(card['simple'])}</p>")
        if card.get("examples"):
            out.append("<ul>" + "".join(f"<li>{_esc(e)}</li>" for e in card["examples"]) + "</ul>")
        out.append(f"<div class='apply'><strong>Apply it:</strong> {_esc(card['apply'])}</div>")
        out.append("</section>")

    # Flashcards
    out.append("<h2>Flashcards</h2>")
    for card in cards:
        out.append(
            f"<details><summary>{_esc(card['cue'])}</summary>"
            f"<p><strong>{_esc(card['term'])}</strong> — {_esc(card['simple'])}</p></details>"
        )

    # Quiz, grouped by level
    out.append("<h2>Check Yourself — 3-Level Quiz</h2>")
    level_names = {1: "Level 1 · Recall", 2: "Level 2 · Understand", 3: "Level 3 · Apply"}
    for level in (1, 2, 3):
        questions = [q for q in quiz if q["level"] == level]
        if not questions:
            continue
        out.append(f"<h3>{level_names[level]}</h3>")
        for q in questions:
            out.append("<div class='quiz-q'>")
            out.append(f"<p><strong>{_esc(q['prompt'])}</strong></p><ol type='A'>")
            for choice in q["choices"]:
                out.append(f"<li>{_esc(choice)}</li>")
            out.append("</ol>")
            answer = q["choices"][q["answer_index"]]
            out.append(f"<details><summary>Answer</summary><p>{_esc(answer)}</p></details>")
            out.append("</div>")

    # Commitments
    if commitments:
        out.append("<h2>Commitments From This Lecture</h2>")
        for item in commitments:
            out.append(
                f"<div class='commit'><strong>{_esc(item['title'])}</strong> — "
                f"{_esc(_COMMIT_LABEL.get(item.get('kind'), 'on'))} {_esc(item['date'])}"
                f"<br><em>\"{_esc(item['quote'])}\"</em></div>"
            )

    out.append("</main><footer>Generated by the Bee Stinger Extension (MIT). "
               "Study-unit format follows TRSS (TruJoe Digital LLC), which is not part of this repository.</footer>")
    out.append("</body></html>")
    return "".join(out)
